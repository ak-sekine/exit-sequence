import type { ActionDefinition, ExpansionEventDefinition, OutcomeDefinition, Predicate } from '../expansion-engine.ts'

const pred = (explanation: string, ...all: NonNullable<Predicate['all']>[number][]): Predicate => ({ explanation, all })
const out = (text: string, powerDelta: number, extra: Omit<OutcomeDefinition, 'text' | 'powerDelta'> = {}): OutcomeDefinition => ({ text, powerDelta, ...extra })
const action = (
  id: string, label: string, detail: string, baseChance: number,
  success: OutcomeDefinition, failure: OutcomeDefinition,
  extra: Pick<ActionDefinition, 'chanceRules' | 'useItem'> = {},
): ActionDefinition => ({ id, label, detail, baseChance, success, failure, ...extra })
const simple = (
  id: string, label: string, detail: string, chance: number, success: string, failure: string,
  successPower = -1, failurePower = -2,
): ActionDefinition => action(id, label, detail, chance, out(success, successPower), out(failure, failurePower))
const event = (
  id: string, title: string, description: string, causalReason: string,
  actions: readonly [ActionDefinition, ActionDefinition, ActionDefinition],
  extra: Pick<ExpansionEventDefinition, 'availableWhen' | 'guarantee' | 'relatedEventIds' | 'followUpEventIds'> = {},
): ExpansionEventDefinition => ({
  id, title, description, zone: 2, availableWhen: pred(causalReason), actions, ...extra,
})
const linkedAvailability = (condition: NonNullable<ExpansionEventDefinition['availableWhen']>, priority: number, reason: string) => ({
  availableWhen: condition,
  guarantee: { when: condition, priority, reason },
})

