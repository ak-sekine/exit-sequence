const action = (
  id: string, label: string, detail: string, baseChance: number,
  success: OutcomeDefinition, failure: OutcomeDefinition,
  extra: Pick<ActionDefinition, 'chanceRules' | 'useItem'> = {},
): ActionDefinition => ({ id, label, detail, baseChance, success, failure, ...extra })

type Choice = readonly [label: string, detail: string, success: string, failure: string, chance?: number]
const normal = (id: string, title: string, description: string, reason: string, choices: readonly [Choice, Choice, Choice]): ExpansionEventDefinition => ({
  id, title, description, zone: 3, availableWhen: pred(reason),
  actions: choices.map(([label, detail, success, failure, chance = 70], i) => action(
    `${id}-${i + 1}`, label, detail, chance, out(success, -1), out(failure, -2),
  )) as unknown as ExpansionEventDefinition['actions'],
})
